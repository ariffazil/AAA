#!/usr/bin/env python3
"""Canon pointer audit -- every rendered AGENTS.md pointer must resolve.

Directive: WELL::SEVERITY_INVERSION_REPAIR::2026-10-14 · CANON REPAIR · ARIF

WHY THIS EXISTS
    /root/AGENTS.md is generated by /root/scripts/render-agents.sh and lists
    canon fragments by absolute path WITH a declared byte size. Four rendered
    pointers were found resolving to files absent from disk -- including
    `agent-relational-interpretation-rules.md`, the I1-I7 canon governing how
    agents may interpret human beings. An agent following the rendered pointer
    hit a dead path with no way to know the doctrine existed, and had to
    reconstruct the rule from memory.

    A pointer that does not resolve is worse than no pointer: it reads as
    "canon is loaded" while nothing is. This script fails closed on that.

WHAT IT CHECKS
    1. Every `- **name** — /abs/path (N bytes). Title` pointer resolves.
    2. Declared byte size matches disk (stale-render detection).
    3. Every `ref:name` in the `> **Fragments:**` line has a pointer, and every
       pointer has a ref -- the two lists must not drift apart.
    4. For any ABSENT pointer, probes git history in the owning repo for
       WITNESSED provenance, so the repair path is restore-from-provenance
       rather than recreate-from-memory.

POLICY (verbatim from the directive)
    Do not recreate missing doctrine from memory. Restore only from witnessed
    provenance. Otherwise mark UNKNOWN or RETIRED.

USAGE
    canon_pointer_audit.py                          # human table; exit 1 on defect
    canon_pointer_audit.py --json                   # machine receipt on stdout
    canon_pointer_audit.py --agents-md P
    canon_pointer_audit.py --allow-retired a,b      # known relocated/superseded

EXIT CODES
    0  every pointer resolves at its declared size
    1  at least one ABSENT pointer, SIZE_DRIFT, or ref/pointer mismatch
    2  the audit itself could not run (missing AGENTS.md, regex drift, crash)
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from datetime import datetime, timezone
from pathlib import Path

DEFAULT_AGENTS_MD = Path("/root/AGENTS.md")

POINTER_RE = re.compile(
    r"^-\s+\*\*(?P<name>[^*]+)\*\*\s+[\u2014-]+\s+(?P<path>/\S+?\.md)"
    r"\s+\((?P<size>\d+)\s+bytes\)\.\s*(?P<title>.*)$"
)
REFS_RE = re.compile(r"\*\*Fragments:\*\*\s*(?P<refs>.+)$")


def _run(cmd: list[str], cwd: Path | None) -> tuple[int, str]:
    try:
        proc = subprocess.run(
            cmd,
            cwd=str(cwd) if cwd else None,
            capture_output=True,
            text=True,
            timeout=60,
        )
        return proc.returncode, (proc.stdout or "").strip()
    except (subprocess.SubprocessError, OSError) as exc:
        return 1, f"<probe error: {exc}>"


def _enclosing_repo(path: Path) -> Path | None:
    for candidate in [path.parent, *path.parent.parents]:
        if (candidate / ".git").exists():
            return candidate
    return None


def _probe_provenance(abs_path: Path) -> dict:
    """Locate witnessed provenance for an absent file. Never invents content.

    `git log -1 -- path` returns the NEWEST commit touching the path, which for
    a deleted file is the DELETING commit -- where the blob no longer exists.
    Probing only that commit reports BLOB_GONE for content that is in fact one
    revision back. So: exclude deletion commits first, then walk history until a
    commit is found that actually holds the blob.
    """
    repo = _enclosing_repo(abs_path)
    if repo is None:
        return {"provenance": "NO_REPO", "commit": None, "recoverable": False}
    try:
        rel = abs_path.relative_to(repo).as_posix()
    except ValueError:
        rel = abs_path.as_posix()

    # Newest non-deleting commit is the usual answer.
    _, candidates = _run(
        ["git", "log", "--all", "--diff-filter=d", "--format=%H", "-n", "20", "--", rel],
        repo,
    )
    shas = [c for c in candidates.splitlines() if c.strip()]
    if not shas:
        # Fall back to full history (covers rename/add-only histories).
        _, allc = _run(["git", "log", "--all", "--format=%H", "-n", "20", "--", rel], repo)
        shas = [c for c in allc.splitlines() if c.strip()]
    if not shas:
        return {
            "provenance": "NO_HISTORY",
            "commit": None,
            "recoverable": False,
            "repo": str(repo),
            "repo_rel": rel,
        }

    for sha in shas:
        rc, _ = _run(["git", "cat-file", "-e", f"{sha}:{rel}"], repo)
        if rc == 0:
            _, blob = _run(["git", "rev-parse", f"{sha}:{rel}"], repo)
            if blob.startswith("<probe error"):
                blob = None
            _, deleted_by = _run(
                ["git", "log", "--all", "--diff-filter=D", "--format=%h %ad %s",
                 "--date=short", "-1", "--", rel],
                repo,
            )
            return {
                "provenance": "WITNESSED",
                "commit": sha,
                "blob": blob,
                "recoverable": True,
                "repo": str(repo),
                "repo_rel": rel,
                "deleted_by": deleted_by or None,
                "restore_cmd": f"git -C {repo} show {sha}:{rel} > {abs_path}",
            }

    return {
        "provenance": "BLOB_GONE",
        "commit": shas[0],
        "blob": None,
        "recoverable": False,
        "repo": str(repo),
        "repo_rel": rel,
    }


def _sha256(path: Path) -> str | None:
    try:
        return hashlib.sha256(path.read_bytes()).hexdigest()
    except OSError:
        return None


def audit(
    agents_md: Path,
    allow_retired: set[str],
    manifest: dict | None = None,
    strict_size: bool = False,
) -> dict:
    if not agents_md.exists():
        return {"ok": False, "fatal": f"AGENTS.md not found at {agents_md}"}

    text = agents_md.read_text(encoding="utf-8", errors="replace")
    pointers: dict[str, dict] = {}
    refs: list[str] = []
    parse_errors: list[str] = []

    for lineno, line in enumerate(text.splitlines(), start=1):
        stripped = line.strip()
        m = POINTER_RE.match(stripped)
        if m:
            name = m.group("name").strip()
            if name in pointers:
                parse_errors.append(f"line {lineno}: duplicate pointer name {name!r}")
            pointers[name] = {
                "name": name,
                "path": m.group("path"),
                "declared_bytes": int(m.group("size")),
                "title": m.group("title").strip(),
                "line": lineno,
            }
            continue
        r = REFS_RE.search(stripped)
        if r:
            refs = [x.strip() for x in r.group("refs").split() if x.strip()]

    if not pointers:
        return {"ok": False, "fatal": "no fragment pointers parsed -- regex drift?"}

    expected_hashes = (manifest or {}).get("fragments", {})
    records: list[dict] = []
    for ref in refs:
        name = ref[4:] if ref.startswith("ref:") else ref
        entry = pointers.get(name)
        if entry is None:
            records.append(
                {
                    "name": name,
                    "verdict": "REF_WITHOUT_POINTER",
                    "detail": f"{ref} is rendered but has no pointer line",
                }
            )
            continue

        path = Path(entry["path"])
        record = dict(entry)
        if not path.exists():
            prov = _probe_provenance(path)
            if name in allow_retired:
                verdict = "RETIRED"
            elif prov.get("recoverable"):
                verdict = "ABSENT_RECOVERABLE"
            elif prov.get("provenance") == "BLOB_GONE":
                verdict = "ABSENT_UNKNOWN"
            else:
                verdict = "ABSENT_NO_PROVENANCE"
            record.update(verdict=verdict)
            record.update(prov)
        else:
            actual = path.stat().st_size
            record["actual_bytes"] = actual
            record["sha256"] = _sha256(path)
            baseline = expected_hashes.get(name)
            if baseline and record["sha256"] != baseline.get("sha256"):
                # Content moved without the render or the manifest being updated.
                record["verdict"] = "HASH_DRIFT"
                record["detail"] = (
                    f"sha256 {str(record['sha256'])[:12]} != manifest "
                    f"{str(baseline.get('sha256'))[:12]} -- canon content changed "
                    f"since the manifest was sealed"
                )
            elif actual != entry["declared_bytes"]:
                record["verdict"] = "SIZE_DRIFT"
                record["detail"] = (
                    f"declared {entry['declared_bytes']} B, on disk {actual} B "
                    "-- rendered pointer is stale"
                )
                if not strict_size:
                    # Ratchet: SIZE_DRIFT is a stale LABEL, not missing canon.
                    # Reported and counted, but not fatal until the render is
                    # refreshed and CI is re-run with --strict-size.
                    record["severity"] = "warning"
            else:
                record["verdict"] = "OK"
        records.append(record)

    ref_names = {(r[4:] if r.startswith("ref:") else r) for r in refs}
    for name, entry in pointers.items():
        if name not in ref_names:
            records.append(
                {
                    "name": name,
                    "verdict": "POINTER_WITHOUT_REF",
                    "detail": (
                        f"pointer at line {entry['line']} is absent from the "
                        f"rendered Fragments list"
                    ),
                }
            )

    defects = [
        r
        for r in records
        if r["verdict"] not in ("OK", "RETIRED") and r.get("severity") != "warning"
    ]
    warnings = [r for r in records if r.get("severity") == "warning"]
    return {
        "ok": not defects and not parse_errors,
        "agents_md": str(agents_md),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "strict_size": strict_size,
        "manifest_used": bool(manifest),
        "pointers_parsed": len(pointers),
        "refs_parsed": len(refs),
        "counts": {
            v: sum(1 for r in records if r["verdict"] == v)
            for v in sorted({r["verdict"] for r in records})
        },
        "parse_errors": parse_errors,
        "records": records,
        "defects": defects,
        "warnings": warnings,
    }


def write_manifest(report: dict, dest: Path) -> int:
    """Seal the current sha256 of every resolving pointer as the CI baseline.

    Stores BOTH the absolute path (for the KVM8-local render audit) and the
    repo-relative path (so the same manifest is verifiable inside a CI checkout,
    where the repo root is not /root/AAA). The rendered index /root/AGENTS.md
    lives OUTSIDE the AAA repo, so CI cannot read it -- the manifest is what
    carries the pointer registry into CI.
    """
    fragments = {}
    for record in report["records"]:
        if not (record.get("sha256") and record.get("path")):
            continue
        abs_path = Path(record["path"])
        repo = _enclosing_repo(abs_path)
        repo_rel = None
        if repo is not None:
            try:
                repo_rel = abs_path.relative_to(repo).as_posix()
            except ValueError:
                repo_rel = None
        fragments[record["name"]] = {
            "path": record["path"],
            "repo_rel": repo_rel,
            "sha256": record["sha256"],
            "bytes": record.get("actual_bytes"),
        }
    payload = {
        "schema": "canon-pointers/v1",
        "generated_at": report["generated_at"],
        "agents_md": report["agents_md"],
        "fragments": fragments,
    }
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    return len(fragments)


def verify_manifest(manifest_path: Path, repo_root: Path) -> dict:
    """CI-side check: every sealed pointer resolves and hashes identically.

    Runs without /root/AGENTS.md, so it works inside a repo checkout. Fails
    closed on a missing file or a hash mismatch -- silent canon mutation is the
    failure mode this exists to catch.
    """
    if not manifest_path.exists():
        return {"ok": False, "fatal": f"manifest not found at {manifest_path}"}
    try:
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return {"ok": False, "fatal": f"manifest unreadable: {exc}"}

    fragments = manifest.get("fragments", {})
    if not fragments:
        return {"ok": False, "fatal": "manifest contains no fragments"}

    records = []
    for name in sorted(fragments):
        entry = fragments[name]
        rel = entry.get("repo_rel") or ""
        target = (repo_root / rel) if rel else Path(entry.get("path", ""))
        record = {"name": name, "repo_rel": rel, "expected_sha256": entry.get("sha256")}
        if not rel:
            record["verdict"] = "NO_REPO_REL"
            record["detail"] = "manifest entry has no repo-relative path"
        elif not target.exists():
            record["verdict"] = "ABSENT"
            record["detail"] = f"{target} does not exist in the checkout"
        else:
            actual = _sha256(target)
            record["actual_sha256"] = actual
            record["actual_bytes"] = target.stat().st_size
            if actual != entry.get("sha256"):
                record["verdict"] = "HASH_DRIFT"
                record["detail"] = (
                    f"sha256 {str(actual)[:12]} != sealed {str(entry.get('sha256'))[:12]}"
                    " -- canon content changed without resealing the manifest"
                )
            else:
                record["verdict"] = "OK"
        records.append(record)

    defects = [r for r in records if r["verdict"] != "OK"]
    return {
        "ok": not defects,
        "mode": "verify-manifest",
        "manifest": str(manifest_path),
        "repo_root": str(repo_root),
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "fragments_checked": len(records),
        "counts": {
            v: sum(1 for r in records if r["verdict"] == v)
            for v in sorted({r["verdict"] for r in records})
        },
        "records": records,
        "defects": defects,
    }


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--agents-md", type=Path, default=DEFAULT_AGENTS_MD)
    ap.add_argument("--json", action="store_true", help="emit machine receipt")
    ap.add_argument(
        "--allow-retired",
        default="",
        help="comma-separated fragment names known to be relocated or "
        "superseded; reported as RETIRED rather than as defects",
    )
    ap.add_argument(
        "--manifest",
        type=Path,
        default=None,
        help="sealed hash manifest to check content against (HASH_DRIFT)",
    )
    ap.add_argument(
        "--write-manifest",
        type=Path,
        default=None,
        help="seal current hashes to this path and exit (F13 action: reseal)",
    )
    ap.add_argument(
        "--verify-manifest",
        type=Path,
        default=None,
        help="CI mode: verify a sealed manifest against --repo-root; does not "
        "require the rendered AGENTS.md",
    )
    ap.add_argument(
        "--repo-root",
        type=Path,
        default=Path.cwd(),
        help="checkout root for --verify-manifest (default: cwd)",
    )
    ap.add_argument(
        "--strict-size",
        action="store_true",
        help="treat SIZE_DRIFT (stale rendered byte label) as fatal",
    )
    args = ap.parse_args(argv)

    try:
        if args.verify_manifest:
            report = verify_manifest(args.verify_manifest, args.repo_root)
        else:
            allow_retired = {
                n.strip() for n in args.allow_retired.split(",") if n.strip()
            }
            manifest = None
            if args.manifest and args.manifest.exists():
                manifest = json.loads(args.manifest.read_text(encoding="utf-8"))
            report = audit(args.agents_md, allow_retired, manifest, args.strict_size)
            if args.write_manifest and "fatal" not in report:
                count = write_manifest(report, args.write_manifest)
                report["manifest_written"] = str(args.write_manifest)
                report["manifest_fragments"] = count
    except Exception as exc:  # noqa: BLE001 -- the audit must never crash CI silently
        print(f"X audit failed to run: {exc}", file=sys.stderr)
        return 2

    if "fatal" in report:
        print(f"X {report['fatal']}", file=sys.stderr)
        return 2

    if args.json:
        json.dump(report, sys.stdout, indent=2, default=str)
        sys.stdout.write("\n")
    else:
        _print_human(report)
    return 0 if report["ok"] else 1


def _print_human(report: dict) -> None:
    """Render either report shape (full audit, or CI verify-manifest)."""
    if "fatal" in report:
        print(f"X {report['fatal']}")
        return

    if report.get("mode") == "verify-manifest":
        print(f"Canon pointer manifest verify - {report['manifest']}")
        print(
            f"  repo_root={report['repo_root']} "
            f"fragments={report['fragments_checked']} counts={report['counts']}"
        )
    else:
        print(f"Canon pointer audit - {report['agents_md']}")
        print(
            f"  pointers={report['pointers_parsed']} refs={report['refs_parsed']} "
            f"counts={report['counts']}"
        )
        for err in report.get("parse_errors", []):
            print(f"  ! {err}")

    for record in report["records"]:
        if record["verdict"] == "OK":
            continue
        target = record.get("repo_rel") or record.get("path") or "?"
        print(f"  [{record['verdict']}] {record['name']} -> {target}")
        if record.get("detail"):
            print(f"      {record['detail']}")
        if record.get("commit"):
            print(
                f"      provenance: {record.get('provenance')} "
                f"commit={record['commit'][:12]}"
            )
            if record.get("restore_cmd"):
                print(f"      restore: {record['restore_cmd']}")
            if record.get("deleted_by"):
                print(f"      deleted_by: {record['deleted_by']}")

    for warning in report.get("warnings", []):
        print(f"  [warn] {warning['name']}: {warning.get('detail', '')}")

    if report["ok"]:
        print("PASS")
    else:
        print(f"FAIL {len(report['defects'])} defect(s)")


if __name__ == "__main__":
    raise SystemExit(main())
